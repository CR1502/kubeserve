def aggregate(rows: list[dict]) -> list[dict]:
    groups: dict[tuple[int, int], list[dict]] = {}
    for r in rows:
        groups.setdefault((r["replicas"], r["concurrency"]), []).append(r)
    out = []
    for (replicas, c), rs in sorted(groups.items()):
        agg = {
            "replicas": replicas,
            "concurrency": c,
            "runs": len(rs),
            "repeats": sorted(r["repeat"] for r in rs),
            "requests": sum(r["requests"] for r in rs),
            "failed": sum(r["failed"] for r in rs),
        }
        for metric in METRICS:
            agg[metric] = stat([r[metric] for r in rs])
        lows = [r["cores_per_pod_lowest"] for r in rs if r["cores_per_pod_lowest"] is not None]
        highs = [r["cores_per_pod_highest"] for r in rs if r["cores_per_pod_highest"] is not None]
        agg["cores_per_pod_lowest"] = round(min(lows), 3) if lows else None
        agg["cores_per_pod_highest"] = round(max(highs), 3) if highs else None
        agg["cpu_limit_cores"] = next((r["cpu_limit_cores"] for r in rs if r["cpu_limit_cores"]), None)
        out.append(agg)
    by = {(a["replicas"], a["concurrency"]): a for a in out}
    for a in out:
        one = by.get((1, a["concurrency"]))
        tok, tok1 = m(a["output_tokens_per_s"]), m(one["output_tokens_per_s"]) if one else None
        a["speedup_vs_1_node"] = ratio(tok, tok1)
        a["scaling_efficiency"] = ratio(tok, a["replicas"] * tok1) if tok1 else None
    return out


def scaling_curve(levels: list[dict], planned_levels: list[int]) -> dict:
    """Throughput per node count at the highest level measured for every node count, and at
    each node count's best level. "Best" needs the node count's whole sweep (every planned
    level measured at least once); a partial sweep has no best level yet."""
    by = {(a["replicas"], a["concurrency"]): a for a in levels}
    replica_counts = sorted({a["replicas"] for a in levels})
    measured = {r: {c for (rr, c) in by if rr == r} for r in replica_counts}
    common = set.intersection(*measured.values()) if measured else set()
    top = max(common) if common else None
    per = []
    for r in replica_counts:
        complete = set(planned_levels) <= measured[r]
        best = max((a for a in levels if a["replicas"] == r and m(a["output_tokens_per_s"]) is not None),
                   key=lambda a: m(a["output_tokens_per_s"]), default=None) if complete else None
        at_top = by.get((r, top)) if top is not None else None
        per.append(
            {
                "replicas": r,
                "sweep_complete": complete,
                "concurrency_levels_measured": sorted(measured[r]),
                "at_top": None if not at_top else {"concurrency": top, "output_tokens_per_s": m(at_top["output_tokens_per_s"]), "runs": at_top["runs"]},
                "best": None if not best else {"concurrency": best["concurrency"], "output_tokens_per_s": m(best["output_tokens_per_s"]), "runs": best["runs"]},
            }
        )
    one = next((p for p in per if p["replicas"] == 1), None)
    for p in per:
        for key in ("at_top", "best"):
            point, ref = p[key], (one or {}).get(key)
            if point and ref:
                point["speedup_vs_1_node"] = ratio(point["output_tokens_per_s"], ref["output_tokens_per_s"])
                point["scaling_efficiency"] = ratio(point["output_tokens_per_s"], p["replicas"] * ref["output_tokens_per_s"])
                point["ideal_linear_tokens_per_s"] = round(p["replicas"] * ref["output_tokens_per_s"], 2)
    return {"top_concurrency": top, "per_replicas": per}


def distribution(rows: list[dict]) -> dict:
    """Per run and level (R >= 2): requests served per node vs. an even split."""
    out = []
    for r in sorted(rows, key=lambda r: (r["repeat"], r["replicas"], r["concurrency"])):
        counts = r["served_per_node"]
        n_nodes, total = len(counts), sum(counts.values())
        if r["replicas"] < 2 or not total:
            continue
        expected = total / n_nodes
        shares = {node: round(n / total, 4) for node, n in sorted(counts.items())}
        chi2 = sum((n - expected) ** 2 / expected for n in counts.values())
        p = chi2_sf(chi2, n_nodes - 1)
        out.append(
            {
                "repeat": r["repeat"],
                "replicas": r["replicas"],
                "concurrency": r["concurrency"],
                "served_per_node": dict(sorted(counts.items())),
                "served_total": total,
                "client_succeeded": r["succeeded"],
                "served_check_match": (r["served_check"] or {}).get("match"),
                "shares": shares,
                "even_share": round(1 / n_nodes, 4),
                "max_deviation_pp": round(100 * max(abs(n / total - 1 / n_nodes) for n in counts.values()), 1),
                "chi2": round(chi2, 3),
                "df": n_nodes - 1,
                "p_value": round(p, 4) if p is not None else None,
            }
        )
    tests = [d for d in out if d["p_value"] is not None]
    worst = max(out, key=lambda d: d["max_deviation_pp"], default=None)
    return {
        "levels": out,
        "tests": len(tests),
        "below_threshold": sum(d["p_value"] < P_THRESHOLD for d in tests),
        "expected_below_threshold_by_chance": round(P_THRESHOLD * len(tests), 2),
        "p_threshold": P_THRESHOLD,
        "min_p_value": min((d["p_value"] for d in tests), default=None),
        "worst_deviation": None if not worst else {k: worst[k] for k in ("repeat", "replicas", "concurrency", "max_deviation_pp", "p_value", "served_total")},
    }


def host_guard(files: list[dict], rows: list[dict]) -> dict:
    per_run = []
    for f in files:
        d = f["data"] or {}
        rs = [r for r in rows if r["repeat"] == d.get("repeat", f["number"])]
        hosts = [r["host"] for r in rs]
        rejected = d.get("rejected_attempts") or []
        kinds: dict[str, int] = {}
        for a in rejected:
            kinds[a.get("kind", "?")] = kinds.get(a.get("kind", "?"), 0) + 1
        per_run.append(
            {
                "run": f["number"],
                "levels_accepted": len(rs),
                "levels_accepted_after_retry": sum(r["attempt"] > 1 for r in rs),
                "swap_limit_mib": (d.get("workload") or {}).get("host_swap_limit_mib"),
                "sleep_limit_s": (d.get("workload") or {}).get("host_max_sleep_s"),
                "max_swapped_out_mb": max((h.get("swapped_out_mb") for h in hosts if h.get("swapped_out_mb") is not None), default=None),
                "swap_used_mb": stat([h.get("swap_used_mb_before") for h in hosts] + [h.get("swap_used_mb_after") for h in hosts], 1),
                "load1_after": stat([h.get("load1_after") for h in hosts], 2),
                "rejected_attempts": len(rejected),
                "rejected_by_kind": kinds,
                "rejected": [
                    {k: a.get(k) for k in ("repeat", "replicas", "concurrency", "attempt", "kind", "reason", "t_utc")} for a in rejected
                ],
            }
        )
    return {
        "per_run": per_run,
        "rejected_attempts_total": sum(p["rejected_attempts"] for p in per_run),
        "max_swapped_out_mb": max((p["max_swapped_out_mb"] for p in per_run if p["max_swapped_out_mb"] is not None), default=None),
        "levels": [
            {"repeat": r["repeat"], "replicas": r["replicas"], "concurrency": r["concurrency"], "attempt": r["attempt"],
             **{k: r["host"].get(k) for k in ("swapped_out_mb", "swap_used_mb_before", "swap_used_mb_after", "load1_before", "load1_after")}}
            for r in rows
        ],
    }


def data_checks(files: list[dict], rows: list[dict]) -> dict:
    mismatches, non_200, warnings, sampled, failed_levels = [], [], [], [], []
    for r in rows:
        where = {"repeat": r["repeat"], "replicas": r["replicas"], "concurrency": r["concurrency"]}
        sc = r["served_check"]
        if sc and not sc.get("match"):
            mismatches.append({**where, "served_total": sc.get("served_total"), "succeeded": sc.get("succeeded")})
        if sc.get("non_200_per_pod"):
            non_200.append({**where, "non_200_per_pod": sc["non_200_per_pod"]})
        for w in r["pod_warnings"]:
            warnings.append({**where, "warning": w})
        if r["pods_sampled"] != r["replicas"]:
            sampled.append({**where, "pods_sampled": r["pods_sampled"]})
        if r["failed"]:
            failed_levels.append({**where, "failed": r["failed"], "requests": r["requests"]})
    setups = []
    for f in files:
        for s in (f["data"] or {}).get("replica_setups") or []:
            problems = []
            if s.get("cpusets_disjoint") is not True:
                problems.append(f"cpusets_disjoint={s.get('cpusets_disjoint')}")
            bad_qos = {p: q for p, q in (s.get("qos_class") or {}).items() if q != "Guaranteed"}
            if bad_qos:
                problems.append(f"QoS {bad_qos}")
            w = s.get("warmup") or {}
            if w.get("cold_pods"):
                problems.append(f"cold pods after warm-up {w['cold_pods']}")
            if w.get("failed"):
                problems.append(f"{w['failed']} warm-up requests failed")
            if problems:
                setups.append({"run": f["number"], "replicas": s.get("replicas"), "problems": problems})
    return {
        "served_check_mismatches": mismatches,
        "non_200_responses": non_200,
        "pod_warnings": warnings,
        "levels_missing_pod_samples": sampled,
        "levels_with_failed_requests": failed_levels,
        "skipped_cpu_sample_ticks": sum(r["skipped_ticks"] or 0 for r in rows),
        "replica_setup_problems": setups,
    }


def comparison(levels: list[dict], original: dict | None, planned_levels: list[int], planned_replicas: list[int]) -> list[dict]:
    if not original:
        return []
    by = {(a["replicas"], a["concurrency"]): a for a in levels}
    out = []
    for o in original["levels"]:
        c = o["concurrency"]
        if c not in planned_levels:
            continue
        mn = {}
        for r in planned_replicas:
            a = by.get((r, c))
            mn[str(r)] = None if not a else {
                "runs": a["runs"],
                **{k: a[k] for k in ("output_tokens_per_s", "throughput_req_per_s", "latency_p50_s", "latency_p95_s", "total_cores_used")},
                "tokens_per_s_vs_original": ratio(m(a["output_tokens_per_s"]), m(o["output_tokens_per_s"])),
            }
        out.append({"concurrency": c, "original": o, "multinode": mn})
    return out


def failure_comparison(failures: list[dict]) -> list[dict]:
    """Each X-retry run next to its no-retry run X."""
    by_name = {f["name"]: f for f in failures if not f.get("error")}
    out = []
    for f in by_name.values():
        if not f["retry"]:
            continue
        base = by_name.get(f["name"].removesuffix("-retry")) if f["name"].endswith("-retry") else None
        if base is None:
            base = next((b for b in by_name.values() if b["scenario"] == f["scenario"] and not b["retry"]), None)
        out.append({"retry": f["name"], "no_retry": base["name"] if base else None})
    return out


