def rel(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def link(target: Path, from_dir: Path) -> str:
    """Relative link from a Markdown file's directory to `target`."""
    return os.path.relpath(target.resolve(), from_dir.resolve())


def node_short(name: str | None) -> str:
    """kubeserve-mn-worker2 -> worker2."""
    match = re.search(r"(worker\d*|control-plane)$", name or "")
    return match.group(1) if match else (name or "?")


def nodes_word(r: int) -> str:
    return f"{r} node{'s' if r != 1 else ''}"


def stat(values, digits: int = 6) -> dict | None:
    vals = [v for v in values if v is not None]
    if not vals:
        return None
    return {"mean": round(mean(vals), digits), "min": round(min(vals), digits), "max": round(max(vals), digits), "n": len(vals)}


def m(st: dict | None) -> float | None:
    return None if not st else st["mean"]


def num(x: float | None, digits: int = 1, suffix: str = "") -> str:
    return "–" if x is None else f"{x:.{digits}f}{suffix}"


def fs(st: dict | None, digits: int = 1, show_range: bool = True) -> str:
    """Mean, plus the min–max range across runs when there are several and they differ."""
    if not st:
        return "–"
    text = f"{st['mean']:.{digits}f}"
    lo, hi = f"{st['min']:.{digits}f}", f"{st['max']:.{digits}f}"
    if show_range and st.get("n", 1) > 1 and lo != hi:
        text += f" ({lo}–{hi})"
    return text


def pct(x: float | None, digits: int = 0) -> str:
    return "–" if x is None else f"{100 * x:.{digits}f}%"


def times(x: float | None) -> str:
    return "–" if x is None else f"{x:.2f}×"


def ratio(a: float | None, b: float | None, digits: int = 6) -> float | None:
    return round(a / b, digits) if a is not None and b else None


def res_text(res: dict | None) -> str:
    """{'cpu': '3', 'memory': '3840Mi'} -> 'cpu 3, memory 3840Mi'."""
    return ", ".join(f"{k} {v}" for k, v in (res or {}).items()) or "–"


def parse_cpuset(cpuset: str | None) -> list[int]:
    cpus: list[int] = []
    for part in (cpuset or "").split(","):
        part = part.strip()
        if "-" in part:
            lo, hi = part.split("-")
            cpus.extend(range(int(lo), int(hi) + 1))
        elif part:
            cpus.append(int(part))
    return cpus


def chi2_sf(x: float, df: int) -> float | None:
    """P(X >= x) for a chi-square distribution with df degrees of freedom (closed forms)."""
    if df < 1 or x < 0:
        return None
    half = x / 2
    if df % 2 == 0:
        term, total = 1.0, 1.0
        for i in range(1, df // 2):
            term *= half / i
            total += term
        return math.exp(-half) * total
    total, term = math.erfc(math.sqrt(half)), 0.0
    for i in range(1, (df - 1) // 2 + 1):
        term = math.sqrt(half) / math.gamma(1.5) if i == 1 else term * half / (i - 0.5)
        total += math.exp(-half) * term
    return total


