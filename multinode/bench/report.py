def _scenario_title(f: dict) -> str:
    if f.get("error") and f.get("scenario") is None:
        return f"`{f['name']}`"
    what = {"node-kill": "worker node killed (`docker kill`)", "process-crash": "vLLM process killed (SIGKILL in one pod)"}.get(f["scenario"], f["scenario"])
    return f"`{f['name']}`: {what}, {'one client retry' if f['retry'] else 'no client retry'}"


def _errors(f: dict) -> str:
    totals: dict[str, int] = {}
    for cats in f["error_categories_by_class"].values():
        for cat, n in cats.items():
            totals[cat] = totals.get(cat, 0) + n
    return ", ".join(f"{cat} {n}" for cat, n in sorted(totals.items(), key=lambda kv: -kv[1])) or "none"


def _phase(f: dict, name: str) -> dict | None:
    return next((p for p in f["phases"] if p.get("phase") == name), None)


def _phase_cell(p: dict | None) -> str:
    return f"{pct(p.get('success_rate'), 0)} / {num(p.get('output_tokens_per_s'), 0)}" if p else "–"


def failure_detail(report: dict, md_dir: Path) -> list[str]:
    fails = report["failure_tests"]
    if fails["status"] == "not run yet":
        return [f"_Not run yet: no `<scenario>/summary.json` under `{report['sources']['failure_dir']}/`._"]
    key_labels, class_labels, phase_labels = _failure_labels()
    lines: list[str] = []
    dirs = report["_failure_dirs"]
    for f in fails["scenarios"]:
        d = dirs[f["name"]]
        lines += [f"### {_scenario_title(f)}", ""]
        if f.get("error"):
            lines += [f"_Could not use this run: {f['error']}._", ""]
            continue
        src = f"[`summary.md`]({link(d / 'summary.md', md_dir)})" if f["has_summary_md"] else "`summary.md` missing"
        lines.append(f"Source: {src} and the raw files in [`{f['name']}/`]({link(d, md_dir)}). Started {f['started_at']}; "
                     f"{f['replicas']} replicas, {f['concurrency']} closed-loop clients, {num(f['timeout_s'], 0)} s client timeout. "
                     f"Victim: `{(f['victim'] or {}).get('pod')}` on `{(f['victim'] or {}).get('node')}`; fault command `{f['fault_command']}`."
                     + (f" Replacement: `{f['replacement_pod'].get('pod')}` on `{f['replacement_pod'].get('node')}`." if f["replacement_pod"] else ""))
        lines.append("")
        valid = "yes" if f["valid"] else "**NO** — " + "; ".join(f["invalid_reasons"])
        lines.append(f"**Result: {f['headline']}; " + (f"recovered {num(f['recovered_after_s'])} s after the fault" if f["recovered"] else "**not recovered**")
                     + f".** Valid: {valid}. Host swap-out during the load: {num(f['host_swapped_out_mb'])} MiB.")
        for w in f["warnings"]:
            lines.append(f"- Warning: {w}")
        lines += ["", "| Event | s after the fault |", "|---|---:|"]
        for key, value in f["key_times_s_after_fault"].items():
            lines.append(f"| {key_labels.get(key, key)} | {num(value) if value is not None else 'not seen'} |")
        lines += ["", "| Outcome | Requests |", "|---|---:|"]
        for c, n in f["by_class"].items():
            lines.append(f"| {class_labels.get(c, c)} | {n} |")
        lines.append(f"| **total** | **{f['requests_total']}** |")
        if f["error_categories_by_class"]:
            lines += ["", "| Failure class | Error | Requests |", "|---|---|---:|"]
            for c, cats in f["error_categories_by_class"].items():
                for cat, n in sorted(cats.items(), key=lambda kv: -kv[1]):
                    lines.append(f"| {class_labels.get(c, c)} | {cat} | {n} |")
        lines += ["", "| Phase | s after the fault | Sent | Succeeded | Failed | Success rate | Output tok/s | p50 / p95 of successes (s) |",
                  "|---|---|---:|---:|---:|---:|---:|---:|"]
        for p in f["phases"]:
            lines.append(f"| {phase_labels.get(p['phase'], p['phase'])} | {num(p.get('from_s'))} → {num(p.get('to_s'))} | {p.get('started')} | "
                         f"{p.get('succeeded')} | {p.get('failed')} | {pct(p.get('success_rate'), 1)} | {num(p.get('output_tokens_per_s'))} | "
                         f"{num(p.get('latency_p50_s'), 2)} / {num(p.get('latency_p95_s'), 2)} |")
        r = f["retry_stats"]
        if r:
            lost = r.get("time_lost_by_masked_requests_s") or {}
            lines += ["", "| Client retry | |", "|---|---:|",
                      f"| attempts sent | {r.get('total_attempts')} |",
                      f"| requests whose first attempt failed | {r.get('first_attempt_failures')} |",
                      f"| retried | {r.get('requests_retried')} |",
                      f"| succeeded on the retry (masked) | {r.get('succeeded_on_retry')} |",
                      f"| failed again on the retry | {r.get('failed_after_retry')} |",
                      f"| failed, not retryable | {r.get('failed_not_retryable')} |",
                      f"| time lost by masked requests, median / max (s) | {num(lost.get('median'), 2)} / {num(lost.get('max'), 2)} |"]
        served = " · ".join(f"{node_short(n)}: {c}" for n, c in sorted(f["served_per_node_from_access_logs"].items())) or "no access logs"
        lines += ["", f"Served per node (HTTP 200 lines in the access logs): {served}. Access-log 200s: {f['access_log_200_total']}; "
                      f"successful attempts seen by the client: {f['client_successful_attempts']}."]
        if f["has_chart"]:
            lines += ["", f"![{f['name']} timeline]({link(d / 'failure_timeline.png', md_dir)})"]
        lines.append("")
    if fails["retry_comparison"]:
        lines += retry_comparison_table(report)
    return lines


def retry_comparison_table(report: dict) -> list[str]:
    by = {f["name"]: f for f in report["failure_tests"]["scenarios"] if not f.get("error")}
    lines = []
    for pair in report["failure_tests"]["retry_comparison"]:
        rt, base = by[pair["retry"]], by.get(pair["no_retry"]) if pair["no_retry"] else None
        lines += [f"### Client retry vs. no retry: `{pair['retry']}`" + (f" vs. `{pair['no_retry']}`" if base else " (no no-retry run to compare yet)"), ""]
        cols = [x for x in (base, rt) if x]
        lines += ["| | " + " | ".join(f"`{c['name']}`" for c in cols) + " |", "|---|" + "---:|" * len(cols)]

        def row(label, fn, cols=cols):
            return f"| {label} | " + " | ".join(fn(c) for c in cols) + " |"

        lines += [
            row("valid", lambda c: "yes" if c["valid"] else "no"),
            row("requests sent", lambda c: str(c["requests_total"])),
            row("requests failed (final outcome)", lambda c: str(c["requests_failed"])),
            row("success rate, whole run", lambda c: pct(c["requests_succeeded"] / c["requests_total"], 1) if c["requests_total"] else "–"),
            row("requests whose first attempt failed", lambda c: str((c["retry_stats"] or {}).get("first_attempt_failures", c["requests_failed"]))),
            row("masked by the retry", lambda c: str((c["retry_stats"] or {}).get("succeeded_on_retry", "–"))),
            row("recovered after (s)", lambda c: num(c["recovered_after_s"])),
            row("errors", _errors),
            "",
        ]
        lines.append("The two are separate runs of the same procedure. The client retry does not change how Kubernetes detects "
                     "and replaces the pod, so differences in those times are run-to-run variation.")
        lines.append("")
    return lines


def failure_readme_block(report: dict, readme_dir: Path) -> str:
    fails = report["failure_tests"]
    lines = [FAILURE_START, "## Failure test results", ""]
    if fails["status"] == "not run yet":
        lines += ["**Not run yet.** `make -C multinode failure` writes `multinode/results/failure/<scenario>/`; "
                  "this section is then generated from each run's `summary.json`.", "", FAILURE_END]
        return "\n".join(lines)
    good = [f for f in fails["scenarios"] if not f.get("error")]
    dirs = report["_failure_dirs"]
    if not good:
        lines += ["No usable failure-test summary yet:", *(f"- `{f['name']}`: {f['error']}" for f in fails["scenarios"]), "", FAILURE_END]
        return "\n".join(lines)
    lines += [f"Generated from `summary.json` in each run's directory. Times are seconds after the fault, as first seen by a "
              "1 s watcher (upper bounds). Requests are counted in the phase in which they were sent. Full tables: "
              f"[`results/results.md`]({link(report['_out_md'], readme_dir)}#failure-tests).", ""]
    head = "| | " + " | ".join(f"[`{f['name']}`]({link(dirs[f['name']] / 'summary.md', readme_dir)})" for f in good) + " |"
    lines += [head, "|---|" + "---:|" * len(good)]

    def row(label, fn):
        return f"| {label} | " + " | ".join(fn(f) for f in good) + " |"

    lines.append(row("Valid run", lambda f: "yes" if f["valid"] else "**no**: " + "; ".join(f["invalid_reasons"])))
    lines.append(row("Load", lambda f: f"{f['replicas']} replicas, {f['concurrency']} clients"))
    def event(f: dict, k: str) -> str:
        times_ = f["key_times_s_after_fault"]
        if k not in times_:
            return "n/a"  # not applicable to this scenario (or no fault was injected)
        if times_[k] is None:
            return "**not recovered**" if k == "recovered" else "not seen"
        return num(times_[k])

    for key, label in FAILURE_ROWS:
        if any(key in f["key_times_s_after_fault"] for f in good):
            lines.append(row(f"{label} (s)", lambda f, k=key: event(f, k)))
    lines.append(row("Requests failed / sent", lambda f: f"**{f['requests_failed']}** / {f['requests_total']}"))
    lines.append(row("… in flight at the fault / sent after it", lambda f: f"{f['by_class'].get('failed_in_flight', 0)} / {f['by_class'].get('failed_after_fault', 0)}"))
    lines.append(row("Errors", _errors))
    for ph, label in (("pre_fault", "sent before the fault (incl. requests killed in flight)"), ("detection", "detection window"), ("degraded", "degraded"), ("post_recovery", "post-recovery")):
        lines.append(row(f"Success rate / tok/s, {label}", lambda f, p=ph: _phase_cell(_phase(f, p))))
    if any(f["retry_stats"] for f in good):
        lines.append(row("Client retry: retried / masked", lambda f: f"{f['retry_stats']['requests_retried']} / {f['retry_stats']['succeeded_on_retry']}" if f["retry_stats"] else "no retry"))
    warn = [f"- `{f['name']}`: {w}" for f in good for w in f["warnings"]]
    if warn:
        lines += ["", "Warnings recorded by the harness:", *warn]
    bad = [f"- `{f['name']}`: {f['error']}" for f in fails["scenarios"] if f.get("error")]
    if bad:
        lines += ["", "Failure-test directories that could not be used:", *bad]
    missing = [n for n in ("node-kill", "process-crash", "node-kill-retry") if n not in {f["name"] for f in fails["scenarios"]}]
    if missing:
        lines += ["", "Not run yet: " + ", ".join(f"`{n}`" for n in missing) + "."]
    first_chart = next((f for f in good if f["has_chart"]), None)
    if first_chart:
        lines += ["", f"![{first_chart['name']} timeline]({link(dirs[first_chart['name']] / 'failure_timeline.png', readme_dir)})"]
    lines += ["", FAILURE_END]
    return "\n".join(lines)


