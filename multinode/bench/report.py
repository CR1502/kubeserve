def load_scaling_files(raw_dir: Path) -> list[dict]:
    files = []
    for path in raw_dir.glob("scaling-run*.json"):
        match = re.fullmatch(r"scaling-run(\d+)\.json", path.name)
        if not match:
            continue
        try:
            data, error = json.loads(path.read_text()), None
        except (OSError, json.JSONDecodeError) as exc:
            data, error = None, f"{type(exc).__name__}: {exc}"
        files.append({"path": path, "number": int(match.group(1)), "data": data, "error": error})
    return sorted(files, key=lambda f: f["number"])


def source_info(f: dict) -> dict:
    d = f["data"] or {}
    wl = d.get("workload") or {}
    measured: dict[int, list[int]] = {}
    for run in d.get("runs") or []:
        measured.setdefault(run["replicas"], []).append(run["concurrency"])
    planned_r, planned_c = wl.get("replica_counts") or [], wl.get("concurrency_levels") or []
    return {
        "file": rel(f["path"]),
        "run": f["number"],
        "repeat": d.get("repeat", f["number"]),
        "status": d.get("status", "unknown") if f["data"] is not None else "unreadable",
        "error": d.get("error") or f["error"],
        "started_utc": d.get("started_utc"),
        "finished_utc": d.get("finished_utc"),
        "replica_order": planned_r,
        "concurrency_levels": planned_c,
        "levels_planned": len(planned_r) * len(planned_c),
        "levels_measured": sum(len(v) for v in measured.values()),
        "measured": [{"replicas": r, "concurrency": sorted(cs)} for r, cs in measured.items()],
        "rejected_attempts": len(d.get("rejected_attempts") or []),
        "used": bool(d.get("runs")),
    }


def exact_summary(run: dict) -> dict:
    """Throughput and latency recomputed from the level's request records at full precision.

    The stored `summary` is rounded (2-3 decimals); averaging rounded values across runs
    and rounding again shifted some last digits. Same definitions as bench.loadgen.summarize.
    """
    reqs = run.get("requests") or []
    if not reqs:
        return {}
    ok = [r for r in reqs if r["ok"]]
    wall = max(r["end"] for r in reqs) - min(r["start"] for r in reqs)
    lat = [r["latency_s"] for r in ok]
    return {
        "throughput_req_per_s": len(ok) / wall,
        "output_tokens_per_s": sum(r["completion_tokens"] for r in ok) / wall,
        "latency_p50_s": percentile(lat, 50),
        "latency_p95_s": percentile(lat, 95),
        "latency_p99_s": percentile(lat, 99),
    }


def flatten(run: dict) -> dict:
    """One measured level of one scaling run -> flat metrics."""
    s = {**(run.get("summary") or {}), **exact_summary(run)}
    res = run.get("resources") or {}
    pods = res.get("pods") or {}
    placement = run.get("placement") or {}
    pod_cores = [p["avg_cores_used"] for p in pods.values() if p.get("avg_cores_used") is not None]
    utils = [p["avg_cpu_utilization_pct"] for p in pods.values() if p.get("avg_cpu_utilization_pct") is not None]
    peaks = [p["peak_working_set_mib"] for p in pods.values() if p.get("peak_working_set_mib") is not None]
    total = res.get("total_avg_cores_used")
    tok = s.get("output_tokens_per_s")
    return {
        "repeat": run.get("repeat"),
        "replicas": run["replicas"],
        "concurrency": run["concurrency"],
        "attempt": run.get("attempt", 1),
        "throughput_req_per_s": s.get("throughput_req_per_s"),
        "output_tokens_per_s": tok,
        "latency_p50_s": s.get("latency_p50_s"),
        "latency_p95_s": s.get("latency_p95_s"),
        "latency_p99_s": s.get("latency_p99_s"),
        "total_cores_used": total,
        "cores_per_pod": mean(pod_cores) if pod_cores else None,
        "cores_per_pod_lowest": min(pod_cores) if pod_cores else None,
        "cores_per_pod_highest": max(pod_cores) if pod_cores else None,
        "cpu_utilization_pct": mean(utils) if utils else None,
        "peak_working_set_mib": max(peaks) if peaks else None,
        "tokens_per_core_second": tok / total if tok is not None and total else None,
        "cores_per_node": {(p.get("node") or placement.get(pod) or pod): p.get("avg_cores_used") for pod, p in pods.items()},
        "cpu_limit_cores": next((p.get("cpu_limit_cores") for p in pods.values() if p.get("cpu_limit_cores")), None),
        "requests": s.get("requests", 0),
        "succeeded": s.get("succeeded", 0),
        "failed": s.get("failed", 0),
        "pods_sampled": len(pods),
        "served_per_node": run.get("served_per_node") or {},
        "served_check": run.get("served_check") or {},
        "pod_warnings": run.get("pod_warnings") or [],
        "skipped_ticks": res.get("skipped_ticks", 0),
        "host": run.get("host") or {},
        "placement": placement,
        "pod_cpusets": run.get("pod_cpusets") or {},
    }


def load_original(path: Path) -> dict | None:
    if not path.exists():
        return None
    d = json.loads(path.read_text())
    levels = []
    for row in d.get("levels", []):
        v = row["vllm"]
        levels.append(
            {
                "concurrency": row["concurrency"],
                "runs": v.get("runs"),
                "requests": v.get("requests"),
                "failed": v.get("failed"),
                **{k: v.get(k) for k in ("throughput_req_per_s", "output_tokens_per_s", "latency_p50_s", "latency_p95_s", "avg_cores_used")},
            }
        )
    return {
        "file": rel(path),
        "generated_utc": d.get("generated_utc"),
        "vllm_runs": (d.get("runs_per_target") or {}).get("vllm"),
        "cluster": (d.get("hardware") or {}).get("cluster"),
        "per_pod_resources": ((d.get("hardware") or {}).get("per_pod_resources") or {}).get("vllm"),
        "levels": levels,
    }


