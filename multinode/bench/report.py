def comparison_table(report: dict) -> list[str]:
    rows = report["comparison_vs_original"]
    reps = report["planned_replica_counts"]
    if not rows:
        return ["_Not available: no original results or no shared concurrency levels._"]
    if not any(v for row in rows for v in row["multinode"].values()):
        return ["_Not run yet: no multi-node level at these concurrencies has been measured._"]
    head = ["Concurrency", "Original single-node tok/s"] + [f"{nodes_word(r)} tok/s" for r in reps]
    head += ["Original p50 / p95 (s)"] + [f"{nodes_word(r)} p50 / p95 (s)" for r in reps]
    lines = ["| " + " | ".join(head) + " |", "|" + "---:|" * len(head)]
    for row in rows:
        o = row["original"]
        cells = [str(row["concurrency"]), fs(o["output_tokens_per_s"])]
        for r in reps:
            v = row["multinode"].get(str(r))
            cells.append(fs(v["output_tokens_per_s"]) if v else "not run yet")
        cells.append(f"{num(m(o['latency_p50_s']))} / {num(m(o['latency_p95_s']))}")
