def replace_block(text: str, start: str, end: str, block: str) -> str | None:
    if start not in text or end not in text:
        return None
    before = text[: text.index(start)]
    after = text[text.index(end) + len(end):]
    return before + block + after


def update_readme(report: dict, readme: Path) -> list[str]:
    if not readme.exists():
        return []
    text = readme.read_text()
    done = []
    new = replace_block(text, RESULTS_START, RESULTS_END, results_readme_block(report, readme.parent))
    if new is not None:
        text, done = new, done + ["results"]
    new = replace_block(text, FAILURE_START, FAILURE_END, failure_readme_block(report, readme.parent))
    if new is not None:
        text, done = new, done + ["failure"]
    readme.write_text(text)
    return done


