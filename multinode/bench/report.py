def status_lines(report: dict) -> list[str]:
    lines = []
    for s in report["sources"]["scaling_runs"]:
        order = ", ".join(map(str, s["replica_order"])) or "?"
        measured = "; ".join(f"{nodes_word(x['replicas'])} at c = {', '.join(map(str, x['concurrency']))}" for x in s["measured"]) or "nothing yet"
        state = {"running": "**still running**", "complete": "complete", "aborted": "**aborted**"}.get(s["status"], f"**{s['status']}**")
        text = (f"- Run {s['run']} (`{Path(s['file']).name}`, node counts in the order {order}): {state}; "
                f"{s['levels_measured']} of {s['levels_planned']} levels measured ({measured}); "
                f"{s['rejected_attempts']} rejected attempt(s).")
        if s["status"] == "aborted" and s["error"]:
            text += f" Abort reason: `{s['error'][:200]}`."
        if s["status"] == "unreadable":
            text += f" Could not be read: `{s['error']}`."
        lines.append(text)
    for n in report["sources"]["missing_runs"]:
        lines.append(f"- Run {n} (`scaling-run{n}.json`): not run yet.")
